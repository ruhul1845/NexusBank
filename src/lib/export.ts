import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import { TransactionDTO, BankAccountDTO } from "@/store/api/bankingApi";
import { formatCurrency } from "./banking";

export function downloadTransactionReceiptPdf(txn: TransactionDTO) {
  const doc = new jsPDF();

  // Header
  doc.setFillColor(30, 27, 75);
  doc.rect(0, 0, 210, 38, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(20);
  doc.text("NexusBank", 18, 18);
  doc.setFontSize(10);
  doc.setTextColor(199, 210, 254);
  doc.text("Official Transaction Receipt", 18, 26);
  doc.text(`Ref: ${txn.referenceId}`, 192, 22, { align: "right" });

  // Body
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(12);
  doc.text("Transaction Summary", 18, 52);

  const rows = [
    ["Reference ID", txn.referenceId],
    ["Date & Time", new Date(txn.createdAt).toLocaleString()],
    ["Transaction Type", txn.type.replace("_", " ")],
    ["Status", txn.status],
    ["Sender Account", txn.senderAccount?.accountNumber || "N/A (External / Bank)"],
    ["Receiver Account", txn.receiverAccount?.accountNumber || "N/A (External / Bank)"],
    ["Amount", formatCurrency(txn.amount)],
    ["Transaction Fee", formatCurrency(txn.fee)],
    ["Total", formatCurrency(txn.amount + txn.fee)],
    ["Description", txn.description],
  ];

  autoTable(doc, {
    startY: 58,
    head: [["Field", "Details"]],
    body: rows,
    theme: "striped",
    headStyles: { fillColor: [79, 70, 229], textColor: 255 },
    styles: { fontSize: 10, cellPadding: 4 },
    columnStyles: { 0: { fontStyle: "bold", cellWidth: 60 } },
  });

  const finalY = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 14;
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text(
    "This receipt was electronically generated by NexusBank Digital Banking System.",
    18,
    finalY
  );

  doc.save(`NexusBank-Receipt-${txn.referenceId}.pdf`);
}

export function downloadStatementCsv(account: BankAccountDTO, transactions: TransactionDTO[]) {
  const headers = ["Date", "Reference ID", "Type", "Description", "Sender", "Receiver", "Amount", "Fee", "Status"];
  const lines = transactions.map((t) => [
    new Date(t.createdAt).toISOString(),
    t.referenceId,
    t.type,
    `"${t.description.replace(/"/g, '""')}"`,
    t.senderAccount?.accountNumber || "N/A",
    t.receiverAccount?.accountNumber || "N/A",
    t.amount.toFixed(2),
    t.fee.toFixed(2),
    t.status,
  ]);

  const csvContent = [headers.join(","), ...lines.map((l) => l.join(","))].join("\n");
  const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `NexusBank-Statement-${account.accountNumber}.csv`;
  a.click();
  URL.revokeObjectURL(url);
}

export function downloadStatementPdf(account: BankAccountDTO, transactions: TransactionDTO[]) {
  const doc = new jsPDF();

  doc.setFillColor(30, 27, 75);
  doc.rect(0, 0, 210, 36, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(18);
  doc.text("NexusBank Account Statement", 14, 17);
  doc.setFontSize(10);
  doc.setTextColor(199, 210, 254);
  doc.text(`Account: ${account.accountNumber} (${account.accountType})`, 14, 26);
  doc.text(`Current Balance: ${formatCurrency(account.balance)}`, 196, 26, { align: "right" });

  autoTable(doc, {
    startY: 44,
    head: [["Date", "Reference", "Type", "Description", "Amount", "Status"]],
    body: transactions.map((t) => [
      new Date(t.createdAt).toLocaleDateString(),
      t.referenceId,
      t.type.replace("_", " "),
      t.description,
      formatCurrency(t.amount),
      t.status,
    ]),
    theme: "grid",
    headStyles: { fillColor: [79, 70, 229], textColor: 255, fontSize: 9 },
    styles: { fontSize: 8.5, cellPadding: 3 },
  });

  doc.save(`NexusBank-Statement-${account.accountNumber}.pdf`);
}
